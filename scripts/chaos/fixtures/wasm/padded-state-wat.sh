#!/usr/bin/env bash
# Prints a WASM processor guest in WebAssembly text whose saved state is exactly BYTES bytes per
# branch, for the restore scenarios that need large guest saves. The guest emits nothing. It counts
# the input batches its branch processed in the first eight bytes of the save, and fills the rest
# once, when the host starts the branch, with xorshift output, so neither the archive nor the
# checkpoint storage compresses the save away. Filling the largest save takes under 200 million
# instructions, within the fuel the restore fixture grants each guest operation. A restored branch
# takes back the whole save it is handed, so it saves the same bytes again, and refuses a save of
# any other size as application state.
set -euo pipefail

usage() {
    printf 'usage: %s BYTES\n' "$(basename "$0")" >&2
}

[[ "$#" -eq 1 ]] || { usage; exit 2; }
bytes="$1"
# The counter needs eight bytes, and the save and a host buffer as large as the save must fit the
# 96 MiB MAX MEMORY of fixtures/restore-state.nspl.
[[ "${bytes}" =~ ^[0-9]+$ ]] && ((bytes >= 8 && bytes <= 47 * 1024 * 1024 && bytes % 8 == 0)) \
    || { printf 'the padded save size must be a multiple of 8 from 8 bytes through 47 MiB\n' >&2; exit 2; }
page=65536
# The save sits at 64 KiB. The buffer the guest hands the host starts at the first page past the
# save, so nothing the host builds or writes there reaches the save: the host writes a save it
# restores into that buffer, and afterwards builds every input as a suffix of a buffer at least that
# large.
base=${page}
end=$((base + bytes))
heap=$(((end + page - 1) / page * page))
heap_pages=$((heap / page))
# The nervix_load_state code that refuses the application state a save carries.
application_state_rejected=-8
cat <<WAT
;; Padded-state WASM processor guest for the external chaos runner, generated by
;; scripts/chaos/fixtures/wasm/padded-state-wat.sh for a ${bytes}-byte save per branch.
(module
  (memory (export "memory") 1)
  (global \$batches (mut i64) (i64.const 0))
  (global \$read_ptr (mut i32) (i32.const 0))
  (global \$read_len (mut i32) (i32.const 0))
  (global \$capacity (mut i32) (i32.const 0))
  (func \$grow (param \$pages i32)
    local.get \$pages memory.size i32.gt_u
    if
      local.get \$pages memory.size i32.sub memory.grow
      i32.const -1 i32.eq
      if unreachable end
    end)
  (func (export "nervix_buffer_ptr") (result i32) global.get \$read_ptr)
  (func (export "nervix_buffer_len") (result i32) global.get \$read_len)
  (func (export "nervix_buffer_capacity") (result i32) global.get \$capacity)
  (func (export "nervix_alloc") (param \$len i32) (result i32)
    local.get \$len i32.const $((heap + page - 1)) i32.add
    i32.const 16 i32.shr_u call \$grow
    local.get \$len global.get \$capacity i32.gt_u
    if
      local.get \$len global.set \$capacity
    end
    i32.const ${heap})
  (func (export "nervix_init") (param i32 i32) (result i32)
    (local \$address i32) (local \$state i64)
    i32.const ${heap_pages} call \$grow
    i32.const $((base + 8)) local.set \$address
    i64.const 0x2545f4914f6cdd1d local.set \$state
    block \$filled
      loop \$fill
        local.get \$address i32.const ${end} i32.ge_u br_if \$filled
        local.get \$state local.get \$state i64.const 13 i64.shl i64.xor local.set \$state
        local.get \$state local.get \$state i64.const 7 i64.shr_u i64.xor local.set \$state
        local.get \$state local.get \$state i64.const 17 i64.shl i64.xor local.set \$state
        local.get \$address local.get \$state i64.store
        local.get \$address i32.const 8 i32.add local.set \$address
        br \$fill
      end
    end
    i32.const 0)
  (func (export "nervix_current_domain_time_nanos") (result i64) (i64.const 0))
  (func (export "nervix_process_batch") (param i32 i32) (result i32)
    global.get \$batches i64.const 1 i64.add global.set \$batches
    i32.const 0)
  (func (export "nervix_on_timeout") (param i64) (result i32) (i32.const 0))
  (func (export "nervix_flush") (result i32) (i32.const 0))
  (func (export "nervix_read_emit") (result i32) (i32.const 0))
  (func (export "nervix_dump_state") (result i32)
    i32.const ${base} global.get \$batches i64.store
    i32.const ${base} global.set \$read_ptr
    i32.const ${bytes} global.set \$read_len
    i32.const ${bytes})
  (func (export "nervix_load_state") (param \$ptr i32) (param \$len i32) (result i32)
    local.get \$len i32.const ${bytes} i32.ne
    if (result i32)
      i32.const ${application_state_rejected}
    else
      i32.const ${base} local.get \$ptr local.get \$len memory.copy
      i32.const ${base} i64.load global.set \$batches
      i32.const 0
    end)
  (func (export "nervix_reset_state") (result i32)
    i64.const 0 global.set \$batches
    i32.const 0)
)
WAT

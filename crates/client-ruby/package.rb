# frozen_string_literal: true

# Package an already-built native extension, then extract that exact gem for conformance.
require 'fileutils'
require 'pathname'
require 'rbconfig'
require 'rubygems/package'
require 'rubygems/installer'

target = Pathname.new(ARGV.fetch(0)).expand_path
artifacts = target.join('client-conformance')
staging = artifacts.join('ruby-package')
installed = artifacts.join('ruby')
FileUtils.rm_rf(staging)
FileUtils.mkdir_p(staging.join('lib/nervix_client'))

library = case RbConfig::CONFIG.fetch('host_os')
          when /darwin/ then 'libnervix_client_ruby.dylib'
          when /mswin|mingw/ then 'nervix_client_ruby.dll'
          else 'libnervix_client_ruby.so'
          end
extension = "nervix_client_ruby.#{RbConfig::CONFIG.fetch('DLEXT')}"
FileUtils.cp(target.join('debug', library), staging.join('lib', extension))
require staging.join('lib', extension).to_s

abi = Nervix::Client::RUBY_ABI
unless abi == RbConfig::CONFIG.fetch('ruby_version')
  abort "the extension targets Ruby #{abi}; package it with that interpreter"
end
File.write(staging.join('lib/nervix_client/build.rb'), <<~RUBY)
  # Generated by the native gem build for this interpreter's ABI.
  module Nervix
    module Client
      BUILD_ABI = #{abi.inspect}
    end
  end
RUBY
FileUtils.cp(File.join(__dir__, 'lib/nervix_client.rb'), staging.join('lib/nervix_client.rb'))
FileUtils.cp(File.expand_path('../../LICENSE.md', __dir__), staging.join('LICENSE.md'))

specification = Gem::Specification.new do |spec|
  spec.name = 'nervix-client'
  spec.version = Gem::Version.new(Nervix::Client::VERSION)
  spec.summary = 'The native Ruby client for Nervix'
  spec.description = 'Sessions, typed columns, subscriptions, clocks and client I/O on the shared Rust host runtime.'
  spec.authors = ['Emergentix, Inc.']
  spec.homepage = 'https://github.com/nervix-io/nervix'
  spec.license = 'Nonstandard'
  spec.platform = Gem::Platform.local
  spec.required_ruby_version = Gem::Requirement.new("~> #{abi.split('.').first(2).join('.')}.0")
  spec.require_paths = ['lib']
  spec.files = ['LICENSE.md', 'lib/nervix_client.rb', 'lib/nervix_client/build.rb', "lib/#{extension}"]
end

gem = Dir.chdir(staging) { Gem::Package.build(specification) }
archive = artifacts.join(gem)
FileUtils.mv(staging.join(gem), archive)
FileUtils.rm_rf(installed)
Gem::Package.new(archive.to_s).extract_files(installed.to_s)
fresh = artifacts.join('ruby-fresh')
FileUtils.rm_rf(fresh)
Gem::Installer.at(archive.to_s, install_dir: fresh.to_s, ignore_dependencies: true,
                  document: [], wrappers: false).install
puts "Native gem: #{archive}"
puts "Probe load path: #{installed.join('lib')}"
puts "Fresh GEM_HOME: #{fresh}"

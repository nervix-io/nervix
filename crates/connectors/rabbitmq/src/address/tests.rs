#[test]
fn hosts_are_read_with_the_url_grammar() {
    for (addr, host) in [
        ("amqp://guest:guest@[::1]:5672/%2f", "::1"),
        ("amqps://guest:guest@[2001:db8::1]:5671/%2f", "2001:db8::1"),
        ("amqp://guest:guest@127.0.0.1:5672/%2f", "127.0.0.1"),
        (
            "amqp://guest:guest@rabbitmq.nervix.test:5672/%2f",
            "rabbitmq.nervix.test",
        ),
        (
            "amqp://guest:guest@rabbitmq.nervix.test.:5672/%2f",
            "rabbitmq.nervix.test.",
        ),
    ] {
        let address = RabbitMqAddress::parse(addr).assured("the address is a valid AMQP URI");
        assert_eq!(address.host(), host, "{addr}");
    }
}

#[test]
fn addresses_that_name_no_broker_are_refused_with_their_reason() {
    for (addr, reason) in [
        ("not a url", RabbitMqAddressError::NotUrl),
        (
            "http://guest:secret@127.0.0.1:5672/%2f",
            RabbitMqAddressError::Scheme,
        ),
        ("guest:secret@127.0.0.1:5672", RabbitMqAddressError::Scheme),
        ("amqp:/%2f", RabbitMqAddressError::MissingHost),
        ("amqp:///%2f", RabbitMqAddressError::MissingHost),
        (
            "amqp:guest:secret@127.0.0.1:5672",
            RabbitMqAddressError::MissingHost,
        ),
        (
            "amqp://guest:secret@127.0.0.1:0/%2f",
            RabbitMqAddressError::ZeroPort,
        ),
        (
            "amqps://guest:secret@[::1]:0/%2f",
            RabbitMqAddressError::ZeroPort,
        ),
        (
            "amqp://guest:secret@127.0.0.1:5672/%2f?heartbeat=soon",
            RabbitMqAddressError::Driver,
        ),
        (
            "amqp://guest:secret@127.0.0.1:5672/%2f?auth_mechanism=kerberos",
            RabbitMqAddressError::Driver,
        ),
        (
            "amqp://guest:secret@127.0.0.1:5672/%ff",
            RabbitMqAddressError::Driver,
        ),
    ] {
        let Err(report) = RabbitMqAddress::parse(addr) else {
            panic!("{addr} must not name a broker");
        };
        assert_eq!(report.current_context(), &reason, "{addr}");
        let reported = format!("{report:?}");
        assert!(
            !reported.contains("secret"),
            "{addr} repeats its credentials: {reported}"
        );
    }
}

#[test]
fn an_address_names_its_scheme_default_port_and_default_credentials() {
    let address =
        RabbitMqAddress::parse("amqps://broker.nervix.test").assured("the address names a broker");
    assert_eq!(address.scheme(), &AMQPScheme::AMQPS);
    assert_eq!(address.port(), 5671);
    assert_eq!(address.uri().vhost, "/");
    assert_eq!(address.uri().authority.userinfo, AMQPUserInfo::default());
    let address =
        RabbitMqAddress::parse("amqp://broker.nervix.test/").assured("the address names a broker");
    assert_eq!(address.scheme(), &AMQPScheme::AMQP);
    assert_eq!(address.port(), 5672);
    assert_eq!(address.uri().vhost, "");
}

/// The characters a generated user name, password or virtual host is written from: letters and
/// digits, which an address carries as they are, and characters it has to percent-encode.
const TEXT: [char; 16] = [
    'a', 'Z', '0', '9', ':', '@', '/', '%', '?', '#', ' ', '.', '-', '_', 'é', '☃',
];

/// The characters a generated host label is written from.
const LABEL: [char; 6] = ['a', 'z', 'Q', '0', '7', '-'];

/// Text drawn from `alphabet`, one character per generated byte.
fn drawn(bytes: &[u8], alphabet: &[char]) -> String {
    let mut drawn = String::new();
    for byte in bytes {
        let index = usize::from(*byte) % alphabet.len();
        drawn.push(alphabet[index]);
    }
    drawn
}

/// `text` as an address carries it: letters and digits as they are, everything else
/// percent-encoded byte by byte.
fn percent_encoded(text: &str) -> String {
    let mut encoded = String::new();
    for character in text.chars() {
        if character.is_ascii_alphanumeric() {
            encoded.push(character);
            continue;
        }
        let mut buffer = [0_u8; 4];
        for byte in character.encode_utf8(&mut buffer).bytes() {
            encoded.push_str(&format!("%{byte:02X}"));
        }
    }
    encoded
}

/// A host as an address writes it and as the parsed address names it.
struct WrittenHost {
    written: String,
    host: String,
}

/// The host a generated address names.
#[derive(Debug, bolero::TypeGenerator)]
enum HostPart {
    /// A name of one to four dot-separated labels.
    Name(
        #[generator(bolero::generator::produce_with::<Vec<Vec<u8>>>().len(1_usize..=4))]
        Vec<Vec<u8>>,
    ),
    Ipv4(u32),
    Ipv6(u128),
}

impl HostPart {
    /// The host as the address writes it and as the parsed address names it, unless a label is
    /// empty.
    fn written(&self) -> Option<WrittenHost> {
        match self {
            Self::Name(labels) => {
                let mut name = String::new();
                for label in labels {
                    let label = drawn(label, &LABEL);
                    if label.is_empty() {
                        return None;
                    }
                    if !name.is_empty() {
                        name.push('.');
                    }
                    name.push_str(&label);
                }
                Some(WrittenHost {
                    written: name.clone(),
                    host: name,
                })
            }
            Self::Ipv4(address) => {
                let address = Ipv4Addr::from(*address).to_string();
                Some(WrittenHost {
                    written: address.clone(),
                    host: address,
                })
            }
            Self::Ipv6(address) => {
                let address = Ipv6Addr::from(*address).to_string();
                Some(WrittenHost {
                    written: format!("[{address}]"),
                    host: address,
                })
            }
        }
    }
}

/// The credentials a generated address names.
#[derive(Debug, bolero::TypeGenerator)]
struct UserPart {
    #[generator(bolero::generator::produce_with::<Vec<u8>>().len(1_usize..=8))]
    username: Vec<u8>,
    password: Option<Vec<u8>>,
}

/// The components a generated address is written from.
#[derive(Debug, bolero::TypeGenerator)]
struct AddressParts {
    tls: bool,
    user: Option<UserPart>,
    host: HostPart,
    port: Option<NonZeroU16>,
    vhost: Option<Vec<u8>>,
    heartbeat: Option<u16>,
    frame_max: Option<u32>,
    channel_max: Option<u16>,
    connection_timeout: Option<u64>,
    auth_mechanism: Option<u8>,
}

/// An address written from generated components, and the URI Lapin connects with for it.
struct WrittenAddress {
    written: String,
    uri: AMQPUri,
}

impl AddressParts {
    /// The address these components write, with the URI it names, unless a component cannot be
    /// written: an empty host label or password, or a virtual host the URL grammar would read as a
    /// dot segment.
    fn written(&self) -> Option<WrittenAddress> {
        let scheme = if self.tls {
            AMQPScheme::AMQPS
        } else {
            AMQPScheme::AMQP
        };
        let mut written = if self.tls {
            "amqps://".to_string()
        } else {
            "amqp://".to_string()
        };
        let mut userinfo = AMQPUserInfo::default();
        if let Some(user) = &self.user {
            userinfo.username = drawn(&user.username, &TEXT);
            written.push_str(&percent_encoded(&userinfo.username));
            if let Some(password) = &user.password {
                let password = drawn(password, &TEXT);
                if password.is_empty() {
                    return None;
                }
                written.push(':');
                written.push_str(&percent_encoded(&password));
                userinfo.password = password;
            }
            written.push('@');
        }
        let host = self.host.written()?;
        written.push_str(&host.written);
        let port = match self.port {
            Some(port) => {
                written.push_str(&format!(":{port}"));
                port.get()
            }
            None => scheme.default_port(),
        };
        let vhost = match &self.vhost {
            Some(vhost) => {
                let vhost = drawn(vhost, &TEXT);
                if vhost == "." || vhost == ".." {
                    return None;
                }
                written.push('/');
                written.push_str(&percent_encoded(&vhost));
                vhost
            }
            None => "/".to_string(),
        };
        let mechanisms = [
            SASLMechanism::AMQPlain,
            SASLMechanism::Anonymous,
            SASLMechanism::External,
            SASLMechanism::Plain,
            SASLMechanism::RabbitCrDemo,
        ];
        let auth_mechanism = self
            .auth_mechanism
            .map(|index| mechanisms[usize::from(index) % mechanisms.len()]);
        let mut options = Vec::new();
        if let Some(frame_max) = self.frame_max {
            options.push(format!("frame_max={frame_max}"));
        }
        if let Some(channel_max) = self.channel_max {
            options.push(format!("channel_max={channel_max}"));
        }
        if let Some(heartbeat) = self.heartbeat {
            options.push(format!("heartbeat={heartbeat}"));
        }
        if let Some(connection_timeout) = self.connection_timeout {
            options.push(format!("connection_timeout={connection_timeout}"));
        }
        if let Some(mechanism) = auth_mechanism {
            options.push(format!("auth_mechanism={}", mechanism.name()));
        }
        if !options.is_empty() {
            written.push('?');
            written.push_str(&options.join("&"));
        }
        let uri = AMQPUri {
            scheme,
            authority: AMQPAuthority {
                userinfo,
                host: host.host,
                port,
            },
            vhost,
            query: AMQPQueryString {
                frame_max: self.frame_max,
                channel_max: self.channel_max,
                heartbeat: self.heartbeat,
                connection_timeout: self.connection_timeout,
                auth_mechanism,
            },
        };
        Some(WrittenAddress { written, uri })
    }
}

#[test]
fn bolero_addresses_name_the_broker_written_into_them() {
    bolero::check!()
        .with_iterations(256)
        .with_max_len(256)
        .with_type::<AddressParts>()
        .for_each(|parts| {
            let Some(address) = parts.written() else {
                return;
            };
            let parsed = match RabbitMqAddress::parse(&address.written) {
                Ok(parsed) => parsed,
                Err(refusal) => panic!("{} names a broker: {refusal:?}", address.written),
            };
            assert_eq!(parsed.uri(), &address.uri, "{}", address.written);
            assert_eq!(
                parsed.host(),
                address.uri.authority.host,
                "{}",
                address.written
            );
            assert_eq!(
                parsed.port(),
                address.uri.authority.port,
                "{}",
                address.written
            );
            assert_eq!(parsed.scheme(), &address.uri.scheme, "{}", address.written);
        });
}
